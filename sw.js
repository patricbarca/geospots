// Service worker de la dirección vieja (GitHub Pages): se desinstala y manda a la dirección nueva.
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (e) => e.waitUntil((async () => {
  for (const k of await caches.keys()) await caches.delete(k);
  await self.registration.unregister();
  for (const c of await self.clients.matchAll({ type: 'window' })) c.navigate('https://geospots.comandia.workers.dev/');
})()));
